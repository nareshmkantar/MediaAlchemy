"""
Tool Validator - Schema-based validation for LLM tool calls.

This module provides validation and normalization for tool calls generated by LLMs,
including:
- Tool name validation with fuzzy matching
- Parameter type checking and coercion
- Required/optional parameter enforcement
- Handling of common LLM hallucinations
"""
