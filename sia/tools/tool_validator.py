# ===== Validation Functions =====

@dataclass
class ValidationResult:
    """Result of tool call validation."""
    valid: bool
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    normalized_tool_name: str = ""
    normalized_params: Dict[str, Any] = field(default_factory=dict)


def normalize_tool_name(tool_name: Union[str, None]) -> Tuple[str, bool]:
    """
    Normalize a potentially hallucinated tool name to the correct name.
    
    Args:
        tool_name: The tool name from LLM (may be hallucinated)
        
    Returns:
        Tuple of (normalized_name, was_corrected)
    """
    if tool_name is None:
        return "", False
        
    # Exact match (including compatibility keys) - always return canonical schema.name
    if tool_name in TOOL_SCHEMAS:
        canonical_name = TOOL_SCHEMAS[tool_name].name
        return canonical_name, canonical_name != tool_name
    
    # Check aliases and case-insensitive canonical names
    tool_name_lower = tool_name.lower().strip()
    
    for canonical_name, schema in TOOL_SCHEMAS.items():
        # Case-insensitive canonical match
        if tool_name_lower == canonical_name.lower():
            return canonical_name, True
            
        # Alias match
        if tool_name_lower in [a.lower() for a in schema.aliases] or tool_name in schema.aliases:
            logger.info(f"Tool name '{tool_name}' normalized to '{canonical_name}' via alias")
            return canonical_name, True
    
    return tool_name, False


def normalize_param_name(tool_schema: ToolSchema, param_name: str) -> Tuple[str, bool]:
    """
    Normalize a potentially hallucinated parameter name.
    
    Args:
        tool_schema: The tool's schema
        param_name: The parameter name from LLM
        
    Returns:
        Tuple of (normalized_name, was_corrected)
    """
    # Check direct match
    for ps in tool_schema.params:
        if ps.name == param_name:
            return param_name, False
    
    # Check aliases
    for ps in tool_schema.params:
        if param_name in ps.aliases:
            logger.debug(f"Param '{param_name}' normalized to '{ps.name}'")
            return ps.name, True
    
    return param_name, False


def coerce_param_type(value: Any, expected_type: type) -> Tuple[Any, bool, str]:
    """
    Attempt to coerce a value to the expected type.
    
    Args:
        value: The value to coerce
        expected_type: The target type
        
    Returns:
        Tuple of (coerced_value, success, error_message)
    """
    if value is None:
        return None, True, ""

    if expected_type is Any:
        return value, True, ""

    if isinstance(value, expected_type):
        return value, True, ""
    
    try:
        if expected_type == int:
            return int(float(value)), True, ""
        elif expected_type == float:
            return float(value), True, ""
        elif expected_type == str:
            return str(value), True, ""
        elif expected_type == bool:
            if isinstance(value, str):
                return value.lower() in ('true', '1', 'yes'), True, ""
            return bool(value), True, ""
        elif expected_type == list:
            if isinstance(value, str):
                # Try to parse as JSON array
                import json
                return json.loads(value), True, ""
            return list(value), True, ""
        elif expected_type == dict:
            if isinstance(value, str):
                import json
                return json.loads(value), True, ""
            return dict(value), True, ""
    except (ValueError, TypeError) as e:
        return value, False, f"Cannot convert {type(value).__name__} to {expected_type.__name__}: {e}"
    
    return value, False, f"Unknown type coercion: {type(value).__name__} to {expected_type.__name__}"


def _normalize_expand_grouped_block_params(params: Dict[str, Any]) -> Dict[str, Any]:
    """Map legacy ``allocate_block_metric`` flat params onto ``allocations`` list."""
    out = dict(params or {})
    if out.get("allocations"):
        for legacy in ("metric_columns", "metric_col", "method", "weight_col"):
            out.pop(legacy, None)
        return out

    metrics = out.pop("metric_columns", None)
    if metrics is None:
        metrics = out.pop("metric_col", None)
    method = str(out.pop("method", "equal") or "equal").strip().lower()
    weight = out.pop("weight_col", None)
    if metrics is None and weight is None and method == "equal":
        return out

    if isinstance(metrics, str):
        metric_list = [metrics]
    elif isinstance(metrics, list):
        metric_list = [str(m) for m in metrics if m is not None and str(m).strip()]
    else:
        metric_list = [str(metrics)] if metrics is not None else []

    if not metric_list:
        return out

    if method not in ("equal", "by_weight"):
        method = "equal"
    out["allocations"] = [
        {"metric_col": m, "method": method, "weight_col": weight} for m in metric_list
    ]
    return out


def normalize_planner_tool_params(tool_name: str, params: Dict[str, Any]) -> Dict[str, Any]:
    """Coerce common LLM parameter mistakes before schema validation."""
    normalized, _ = normalize_tool_name(str(tool_name or "").strip())
    if normalized == "transform.expand_grouped_block":
        return _normalize_expand_grouped_block_params(params)
    return dict(params or {})


def validate_tool_call(tool_call: Dict[str, Any]) -> ValidationResult:
    """
    Validate and normalize a tool call from LLM.
    
    Args:
        tool_call: Dict with 'tool' and 'params' keys
        
    Returns:
        ValidationResult with validation status and normalized values
    """
    result = ValidationResult(valid=True)
    
    if not isinstance(tool_call, dict):
        result.valid = False
        result.errors.append(f"Tool call must be a dictionary, got {type(tool_call).__name__}")
        return result

    tool_name = tool_call.get("tool", "")
    params = normalize_planner_tool_params(tool_name, tool_call.get("params", {}))
    
    # Normalize tool name
    normalized_name, was_corrected = normalize_tool_name(tool_name)
    result.normalized_tool_name = normalized_name
    
    if was_corrected:
        result.warnings.append(f"Tool name '{tool_name}' corrected to '{normalized_name}'")
    
    # Check if tool exists
    if normalized_name not in TOOL_SCHEMAS:
        result.valid = False
        result.errors.append(f"Unknown tool: '{tool_name}'")
        
        # Suggest alternatives
        all_tools = list(TOOL_SCHEMAS.keys())
        suggestions = difflib.get_close_matches(tool_name, all_tools, n=3, cutoff=0.4)
        if suggestions:
            result.errors.append(f"Did you mean: {suggestions}?")
        
        return result
    
    tool_schema = TOOL_SCHEMAS[normalized_name]
    normalized_params = {}
    
    # Normalize and validate parameters
    for param_name, param_value in params.items():
        norm_name, was_param_corrected = normalize_param_name(tool_schema, param_name)
        
        if was_param_corrected:
            result.warnings.append(f"Param '{param_name}' corrected to '{norm_name}'")
        
        param_schema = tool_schema.get_param_schema(norm_name)
        
        if param_schema is None:
            # Unknown parameter - warn but don't fail
            result.warnings.append(f"Unknown parameter '{param_name}' for tool '{normalized_name}'")
            normalized_params[param_name] = param_value
            continue
        
        # Type coercion
        coerced_value, success, error_msg = coerce_param_type(param_value, param_schema.param_type)
        
        if not success:
            result.valid = False
            result.errors.append(f"Parameter '{norm_name}': {error_msg}")
        else:
            if coerced_value != param_value:
                result.warnings.append(f"Parameter '{norm_name}' coerced from {type(param_value).__name__} to {param_schema.param_type.__name__}")
            normalized_params[norm_name] = coerced_value
    
    # Check required parameters
    for required_param in tool_schema.get_required_params():
        if required_param not in normalized_params:
            # Check if there's a default
            param_schema = tool_schema.get_param_schema(required_param)
            if param_schema and param_schema.default is not None:
                normalized_params[required_param] = param_schema.default
                result.warnings.append(f"Using default for '{required_param}': {param_schema.default}")
            else:
                result.valid = False
                result.errors.append(f"Missing required parameter: '{required_param}'")
    
    # Add defaults for optional parameters if not provided
    for ps in tool_schema.params:
        if not ps.required and ps.name not in normalized_params and ps.default is not None:
            normalized_params[ps.name] = ps.default
    
    result.normalized_params = normalized_params
    
    return result


def validate_tool_sequence(tool_calls: List[Dict]) -> Tuple[List[Dict], List[str]]:
    """
    Validate and normalize a sequence of tool calls.
    
    Args:
        tool_calls: List of tool call dicts
        
    Returns:
        Tuple of (normalized_tool_calls, all_errors)
    """
    normalized_calls = []
    all_errors = []
    
    for i, tool_call in enumerate(tool_calls):
        result = validate_tool_call(tool_call)
        
        if result.valid:
            normalized_calls.append({
                "step": tool_call.get("step", i + 1),
                "tool": result.normalized_tool_name,
                "params": result.normalized_params,
                "description": tool_call.get("description", ""),
                "_validation_warnings": result.warnings
            })
        else:
            all_errors.extend([f"Step {i+1}: {e}" for e in result.errors])
            # Include the original call but mark it as invalid
            # Safe unpack: if not a dict, wrap it
            source_info = tool_call if isinstance(tool_call, dict) else {"raw_input": tool_call}
            normalized_calls.append({
                **source_info,
                "_validation_errors": result.errors,
                "_valid": False
            })
        
        if result.warnings:
            logger.info(f"Tool call {i+1} warnings: {result.warnings}")
    
    # ===== Inter-Tool Dependency Validation =====
    dep_warnings = _validate_tool_dependencies(normalized_calls)
    if dep_warnings:
        all_errors.extend(dep_warnings)
        logger.warning(f"Tool sequence dependency issues: {dep_warnings}")

    stage_warnings = _validate_stage_monotonicity(normalized_calls)
    if stage_warnings:
        all_errors.extend(stage_warnings)
        logger.warning(f"Tool sequence stage order issues: {stage_warnings}")

    return normalized_calls, all_errors


# After reshape (80); before validation (90). Unknown / unmapped tools run late but before verify.* .
_TOOL_SORT_UNKNOWN_FALLBACK = 88

# Immediately after layout.extract / layout.stack (23), before fill/expand cleanup.
_TOOL_SORT_FILTER_SUMMARIES_AFTER_EXTRACT = 24

# After column_typing (40), before date_normalisation (50) — template metric names exist.
_TOOL_SORT_EXPAND_GROUPED_BLOCK = 45

# After value_standardisation (70) when block metric tools need delimiter columns intact.
_TOOL_SORT_DROP_AFTER_BLOCK_METRICS = 72

_BLOCK_METRIC_TOOLS = frozenset(
    {
        "transform.classify_metric_level",
        "transform.allocate_block_metric",
        "transform.expand_grouped_block",
        "transform.infer_block_boundary_columns",
    }
)


def _plan_uses_block_metric_tools(tool_calls: List[Dict[str, Any]]) -> bool:
    for tc in tool_calls or []:
        if not isinstance(tc, dict):
            continue
        normalized, _ = normalize_tool_name(str(tc.get("tool") or "").strip())
        if normalized in _BLOCK_METRIC_TOOLS:
            return True
    return False


# Re-running these with identical params is a no-op, so a repeat is planner noise.
# Excludes tools whose repeats are meaningful (calculate, map_values, add_column with
# different targets are already distinguished by their params).
_IDEMPOTENT_ON_REPEAT = frozenset(
    {
        "layout.extract",
        "layout.stack",
        "transform.rename",
        "transform.type_cast",
        "transform.format",
        "transform.add_column",
        "transform.apply_column_rules",
        "transform.reorder_columns",
        "transform.sort_rows",
        "transform.drop_columns",
        "transform.fill_merged",
        "transform.filter_summaries",
        "transform.filter_empty",
        "transform.deduplicate",
        "transform.aggregate_weekly",
        "transform.expand_period_to_daily",
        "transform.infer_granularity_expand_to_daily",
        "transform.date_range_to_weekly",
        "verify.schema",
    }
)


def _params_fingerprint(params: Any) -> str:
    try:
        return json.dumps(params, sort_keys=True, default=str)
    except (TypeError, ValueError):
        return repr(params)


def dedupe_redundant_tool_calls(
    tool_calls: List[Dict[str, Any]],
) -> Tuple[List[Dict[str, Any]], List[str]]:
    """Drop repeat calls of idempotent tools with identical params.

    The replanner regenerates a whole plan from the grid, so it commonly restates
    steps that the previous plan (or the verifier's suggestions) already contain.
    Executing them again is wasted work and produces confusing "already exists;
    no change" outcomes in the trace.

    Returns ``(kept_calls, notes)``.
    """
    if not tool_calls:
        return list(tool_calls or []), []

    seen: Set[Tuple[str, str]] = set()
    kept: List[Dict[str, Any]] = []
    notes: List[str] = []

    for tc in tool_calls:
        if not isinstance(tc, dict):
            kept.append(tc)
            continue
        normalized, _ = normalize_tool_name(str(tc.get("tool") or "").strip())
        if not normalized or normalized not in _IDEMPOTENT_ON_REPEAT:
            kept.append(tc)
            continue
        key = (normalized, _params_fingerprint(tc.get("params")))
        if key in seen:
            notes.append(f"{normalized} (identical params)")
            continue
        seen.add(key)
        kept.append(tc)

    if notes:
        logger.info("Dropped %s redundant tool call(s): %s", len(notes), "; ".join(notes[:8]))
    return kept, notes


def sort_tool_calls_by_pipeline_stage(tool_calls: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Stable-sort tool calls by nominal pipeline stage (pipeline_catalog.stage_sort_key).

    Preserves planner order within the same stage. Fixes common LLM mistakes such as
    value-standardisation tools before date normalisation.
    """
    from . import pipeline_catalog

    if not tool_calls:
        return tool_calls

    defer_drop = _plan_uses_block_metric_tools(tool_calls)

    def primary_sort_key(tc: Dict[str, Any], orig_index: int) -> Tuple[int, int]:
        if not isinstance(tc, dict):
            return (_TOOL_SORT_UNKNOWN_FALLBACK, orig_index)
        raw = tc.get("tool", "")
        normalized, _ = normalize_tool_name(raw)
        if not normalized:
            return (_TOOL_SORT_UNKNOWN_FALLBACK, orig_index)
        if defer_drop and normalized == "transform.drop_columns":
            return (_TOOL_SORT_DROP_AFTER_BLOCK_METRICS, orig_index)
        if normalized == "transform.filter_summaries":
            return (_TOOL_SORT_FILTER_SUMMARIES_AFTER_EXTRACT, orig_index)
        if normalized == "transform.expand_grouped_block":
            return (_TOOL_SORT_EXPAND_GROUPED_BLOCK, orig_index)
        stage = pipeline_catalog.stage_for_tool(normalized)
        if stage is None:
            return (_TOOL_SORT_UNKNOWN_FALLBACK, orig_index)
        return (pipeline_catalog.stage_sort_key(stage), orig_index)

    indexed = list(enumerate(tool_calls))
    indexed.sort(key=lambda pair: primary_sort_key(pair[1], pair[0]))
    return [tc for _i, tc in indexed]


def _validate_stage_monotonicity(tool_calls: List[Dict]) -> List[str]:
    """
    Warn when consecutive valid tools violate nominal pipeline stage order.

    Uses primary stage sort_keys from pipeline_catalog. Unknown tools are skipped.
    """
    from . import pipeline_catalog

    warnings: List[str] = []
    valid_sequence: List[Tuple[int, str, int]] = []  # (index, tool_name, sort_key)

    for i, tc in enumerate(tool_calls):
        if not isinstance(tc, dict) or tc.get("_valid") is False:
            continue
        raw_name = tc.get("tool", "")
        normalized, _ = normalize_tool_name(raw_name)
        if not normalized:
            continue
        stage = pipeline_catalog.stage_for_tool(normalized)
        if stage is None:
            continue
        sk = pipeline_catalog.stage_sort_key(stage)
        valid_sequence.append((i, normalized, sk))

    for j in range(1, len(valid_sequence)):
        prev_i, prev_name, prev_sk = valid_sequence[j - 1]
        curr_i, curr_name, curr_sk = valid_sequence[j]
        if curr_sk < prev_sk:
            warnings.append(
                "Stage order: "
                f"step {curr_i + 1} `{curr_name}` (pipeline stage sort_key={curr_sk}) "
                f"follows step {prev_i + 1} `{prev_name}` (sort_key={prev_sk}); "
                "nominal pipeline expects non-decreasing stage order except valid layout pre-steps."
            )
    return warnings


def _validate_tool_dependencies(tool_calls: List[Dict]) -> List[str]:
    """
    Validate logical dependencies between tools in a sequence.
    
    Rules:
    1. Extract/Stack must come before reshape, enrichment, or validation tools
    2. header.collapse can only be used on raw grids (before extract/stack)
    3. validate_schema can be a checkpoint; final-output validation is enforced elsewhere
    4. map_values/rename/format need data to exist (after extract/stack)
    5. melt/unpivot require extract or stack to have been done first
    
    Returns:
        List of warning messages for dependency violations
    """
    warnings = []
    
    tool_names = [tc.get("tool", "") for tc in tool_calls if tc.get("_valid", True)]
    
    if not tool_names:
        return warnings
    
    # Categorize tools
    extraction_tools = {"layout.extract", "layout.stack"}
    pre_extraction_tools = {"layout.merge_headers"}
    reshape_tools = {"transform.unpivot", "layout.unpivot_matrix"}
    layout_cleanup_tools = {
        "transform.filter_summaries",
        "transform.fill_merged",
        "transform.unmerge_and_fill",
        "transform.densify",
    }
    enrichment_tools = {"transform.map_values", "transform.type_cast", "transform.format",
                        "transform.calculate", "transform.scale_values",
                        "transform.date_range_to_weekly", "transform.expand_date_range_to_daily",
                        "transform.expand_date_range_to_weekly", "transform.aggregate_weekly",
                        "transform.build_date_from_parts", "transform.expand_period_to_daily",
                        "transform.infer_granularity_expand_to_daily",
                        "transform.allocate_block_metric",
                        "transform.classify_metric_level",
                        "transform.infer_block_boundary_columns"}
    validation_tools = {"verify.schema", "validate.cross_source_union"}
    
    has_extraction = any(t in extraction_tools for t in tool_names)
    
    for i, tool_name in enumerate(tool_names):
        # Rule 1: Reshape tools need extraction first
        if tool_name in reshape_tools and not has_extraction:
            earlier = tool_names[:i]
            if not any(t in extraction_tools for t in earlier):
                warnings.append(
                    f"Dependency: '{tool_name}' at step {i+1} requires extract/stack first"
                )
        
        # Rule 2: header.collapse must be before extract/stack
        if tool_name in pre_extraction_tools:
            later = tool_names[i+1:]
            if not any(t in extraction_tools for t in later) and has_extraction:
                # collapse is after extraction — this corrupts data
                earlier = tool_names[:i]
                if any(t in extraction_tools for t in earlier):
                    warnings.append(
                        f"Dependency: '{tool_name}' at step {i+1} should be BEFORE extract/stack, "
                        f"not after — using it post-extraction corrupts data"
                    )
        
        # Rule 3: verify.schema is allowed as a source-level checkpoint.
        # The pipeline can still run post-verify work (multi-source collation,
        # deferred grain tools, final layout) before the final output is complete.
        
        # Rule 4: Enrichment / layout cleanup tools need data (after extract/stack)
        if tool_name in enrichment_tools | layout_cleanup_tools and has_extraction:
            earlier = tool_names[:i]
            if not any(t in extraction_tools for t in earlier):
                warnings.append(
                    f"Dependency: '{tool_name}' at step {i+1} operates on data — "
                    f"ensure extract/stack runs first"
                )

        # Rule 5: Summary filter before rename / block metric tools (flat-table cleanup)
        if tool_name in (
            "transform.rename",
            "transform.type_cast",
            "transform.expand_grouped_block",
            "transform.allocate_block_metric",
            "transform.classify_metric_level",
        ):
            earlier = tool_names[:i]
            if has_extraction and "transform.filter_summaries" not in earlier:
                warnings.append(
                    f"Dependency: '{tool_name}' at step {i+1} should run after "
                    f"transform.filter_summaries when the sheet may contain Total/Subtotal rows"
                )
    
    return warnings


def is_destructive_tool(tool_name: str) -> bool:
    """Check if a tool is marked as destructive (requires HITL confirmation)."""
    normalized, _ = normalize_tool_name(tool_name)
    if normalized in TOOL_SCHEMAS:
        return TOOL_SCHEMAS[normalized].destructive
    return False


def get_destructive_tools(tool_calls: List[Dict]) -> List[str]:
    """Get list of destructive tools in a tool call sequence."""
    destructive = []
    for tc in tool_calls:
        tool_name = tc.get("tool", "")
        if is_destructive_tool(tool_name):
            destructive.append(tool_name)
    return list(set(destructive))
