# ===== Tool Schema Registry =====

@dataclass
class ParamSchema:
    """Schema for a tool parameter."""
    name: str
    param_type: type  # int, float, str, list, dict, bool
    required: bool = True
    default: Any = None
    description: str = ""
    aliases: List[str] = field(default_factory=list)  # Common hallucinated names


@dataclass
class ToolSchema:
    """Schema for a transformation tool."""
    name: str
    description: str
    params: List[ParamSchema]
    aliases: List[str] = field(default_factory=list)  # Common hallucinated names
    destructive: bool = False  # If True, requires HITL confirmation
    
    def get_required_params(self) -> List[str]:
        """Get list of required parameter names."""
        return [p.name for p in self.params if p.required]
    
    def get_optional_params(self) -> List[str]:
        """Get list of optional parameter names."""
        return [p.name for p in self.params if not p.required]
    
    def get_param_schema(self, name: str) -> Optional[ParamSchema]:
        """Get schema for a parameter by name or alias."""
        for p in self.params:
            if p.name == name or name in p.aliases:
                return p
        return None


